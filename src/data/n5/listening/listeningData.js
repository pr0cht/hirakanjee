/**
 * Returns a randomized 10-question listening quiz sampled across all 6 tracks.
 * Guarantees balanced coverage of Level 1 tasks, Level 2 conversations,
 * and the four core ~te form structures (~te kudasai, ~te imasu, ~te mo ii desu ka, ~te ~te).
 */
export function getRandomListeningQuiz(count = 10) {
  const tracks = [1, 2, 3, 4, 5, 6];
  const selected = [];

  // Pick at least 1 from each of the 6 tracks
  for (const t of tracks) {
    const questionsInTrack = listeningQuizBank.filter((q) => q.track === t);
    if (questionsInTrack.length > 0) {
      const randIdx = Math.floor(Math.random() * questionsInTrack.length);
      selected.push(questionsInTrack[randIdx]);
    }
  }

  // Fill remainder up to count from across the bank
  if (selected.length < count) {
    const remaining = listeningQuizBank.filter((q) => !selected.some((s) => s.id === q.id));
    const shuffledRem = [...remaining].sort(() => Math.random() - 0.5);
    selected.push(...shuffledRem.slice(0, count - selected.length));
  }

  // Final random shuffle
  return selected.sort(() => Math.random() - 0.5).slice(0, count);
}
